// 动态文案的正则映射（key 未命中时兜底），如 zod 的"不能超过 N 个字符"
const patterns: Array<{ test: RegExp; en: string; ko: string }> = [
  { test: /^不能超过 (\d+) 个字符$/, en: "Must be at most $1 characters", ko: "$1자를 초과할 수 없습니다" },
];

export type TranslateVars = Record<string, string | number>;

export function translate(locale: Locale, text: string, vars?: TranslateVars): string {
  let result = text;
  if (locale === "en-US") result = en[text] ?? applyPattern(text, "en") ?? text;
  else if (locale === "ko-KR") result = ko[text] ?? applyPattern(text, "ko") ?? text;
  if (vars) {
    for (const [key, value] of Object.entries(vars)) {
      result = result.replaceAll(`{${key}}`, String(value));
    }
  }
  return result;
}

function applyPattern(text: string, lang: "en" | "ko"): string | null {
  for (const pattern of patterns) {
    if (pattern.test.test(text)) return text.replace(pattern.test, pattern[lang]);
  }
  return null;
}
